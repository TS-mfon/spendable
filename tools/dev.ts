import {createServer} from 'node:http';
import {resolve} from 'node:path';
import {createServer as createViteServer} from 'vite';
import {createRuntime} from './runtime.ts';
const runtime=await createRuntime();
const server=createServer(runtime.app);
const vite=await createViteServer({configFile:false,root:resolve('web'),server:{middlewareMode:true,hmr:{server},fs:{allow:[process.cwd()]}},appType:'spa'});
runtime.app.use(vite.middlewares);
server.listen(runtime.config.port,'127.0.0.1',()=>console.log('Spendable running at '+runtime.config.origin));
for(const signal of ['SIGTERM','SIGINT'] as const)process.once(signal,()=>{server.close(async()=>{await vite.close();await runtime.close();process.exit(0);});});
